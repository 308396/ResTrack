-- research_create.sql
-- PostgreSQL script for the Research Management Database.

CREATE TABLE grant_types (
    grant_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_type_name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE researchers (
    staff_no INTEGER PRIMARY KEY,
    researcher_name VARCHAR(150) NOT NULL
);

CREATE TABLE research_projects (
    research_id INTEGER PRIMARY KEY,
    so_code INTEGER NOT NULL UNIQUE,
    grant_type_id INTEGER NOT NULL REFERENCES grant_types(grant_type_id),
    research_title VARCHAR(300) NOT NULL,
    start_date DATE NOT NULL,
    expected_date DATE NOT NULL,
    end_date DATE,
    research_status VARCHAR(80) NOT NULL,
    detail TEXT,
    staff_no INTEGER NOT NULL REFERENCES researchers(staff_no),
    CHECK (expected_date >= start_date),
    CHECK (end_date IS NULL OR end_date >= start_date)
);
